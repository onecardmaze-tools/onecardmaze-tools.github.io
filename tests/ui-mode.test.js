app.tap({x:300,y:800});settle();app.spin(1);settle();
const beforeMove=route();app.tap({x:300,y:600});h.tick();app.undoOnce();
assert.equal(route(),beforeMove,'Undo during motion restores the command start');
app.tap({x:300,y:600});settle();
const full=route(),end=S.trail.length-1;
// Checkpoints survive portable/local state restoration.
